/*
 * 预处理指令：以 # 开头，在编译之前由预处理器处理。
 *
 * 这一行把标准库头文件 iostream 的内容“复制”到此处。
 * iostream 声明了标准输入输出流，其中就包括 std::cout。
 *
 * 注意：预处理指令不以分号结尾。
 */
#include <iostream>

/*
 * 函数定义：
 *
 *     int main()
 *
 *   int    返回类型：main 把整数结果交给运行环境
 *   main   函数名：C++ 标准约定的程序入口
 *   ()     参数列表：空括号表示 main 不接受参数
 *
 *  main 不是关键字，而是标准约定的入口函数名。
 *  C++ 区分大小写：Main、MAIN 都不是 main。
 */
int main()
{
    /*
     * 表达式语句：
     *
     *     std::cout << "Hello, World!\n";
     *
     *   std::cout             标准输出流对象
     *   <<                    流插入运算符
     *   "Hello, World!\n"     字符串字面量
     *   ;                     表达式语句的结束
     *
     * std:: 是命名空间限定。cout 住在 std 里；
     * 不写 std:: 而直接写 cout，编译器不知道你说的是哪一个 cout。
     *
     * "\n" 是一个转义序列，表示换行符。
     * 它在字符串中只占一个字符，不是反斜杠加字母 n。
     */
    std::cout << "Hello, World!\n";

    /*
     * return 语句：结束 main，并把 0 返回给运行环境。
     *
     * 0 表示程序正常结束；非 0 通常表示失败。
     * 在 C++ 中，main 执行到右花括号时也会隐式返回 0，
     * 但显式写出来更清楚。
     */
    return 0;
}
